def pick(index=None, seed=None):
    """Return one tip. Cycles deterministically when given an index."""
    if index is not None:
        return TIPS[index % len(TIPS)]
    if seed is not None:
        h = sum(ord(c) for c in str(seed))
        return TIPS[h % len(TIPS)]
    import random
    return random.choice(TIPS)


def caption(tip):
    """Facebook / Telegram caption for a tip."""
    lines = [tip["title"], ""]
    for b in tip["body"]:
        lines.append(f"• {b}")
    if tip.get("cta"):
        lines += ["", tip["cta"]]
    tags = ["#وظائف_السودان", "#تقديم_للوظائف"] + tip.get("tags", [])
    lines += ["", " ".join(tags)]
    return "\n".join(lines)
